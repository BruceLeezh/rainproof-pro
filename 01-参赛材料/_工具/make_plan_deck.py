def add(spec):
    kind, title, en, chapter, payload, nt = spec
    sl = prs.slides.add_slide(BLANK)
    if kind == "cover":
        s_cover(sl, payload)
    elif kind == "closing":
        s_closing(sl, payload)
    else:
        chrome(sl, title, en, chapter=chapter,
               num=f"{len(prs.slides):02d} / 30")
        {"bullets": s_bullets, "rows": s_rows, "table": s_table, "cards": s_cards,
         "kv": s_kv, "steps": s_steps, "layers": s_layers, "two": s_two}[kind](sl, payload)
    notes(sl, nt)


