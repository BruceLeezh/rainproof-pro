def s_cover(sl, d):
    R(sl, 0, 0, W, H, fill=BG)
    BAR(sl)
    kicker(sl, X0, 1.05, "RAINPROOF · 项目计划书 · 2026.11", color=CYAN, size=12)
    T(sl, X0, 1.62, 10.6, 1.20, d["title"], size=44, bold=True, ls=1.10, wrap=False)
    T(sl, X0, 2.92, 10.6, 0.50, d["sub"], size=20, color=CYAN, wrap=False)
    RULE(sl, X0, 3.62, 7.2, a=18, h=0.012)
    y = 3.92
    for line in d["meta"]:
        T(sl, X0, y, 10.6, 0.30, line, size=13, alpha=72)
        y += 0.40
    T(sl, X0, 6.62, 10.6, 0.30, d.get("foot", ""), size=11.5, font=MONO, alpha=40)


def s_bullets(sl, d):
    y = TOP0
    for it in d["items"]:
        txt, sub = (it, None) if isinstance(it, str) else it
        R(sl, X0, y + 0.10, 0.055, 0.20, fill=CYAN)
        T(sl, X0 + 0.24, y, 10.95, 0.34, txt, size=14.5, ls=1.22)
        y += 0.40
        if sub:
            T(sl, X0 + 0.24, y - 0.04, 10.95, 0.30, sub, size=11.5, alpha=64, ls=1.25)
            y += 0.30
        y += 0.14


def s_rows(sl, d):
    """左边标签列 + 右边正文（一页纸摘要用）"""
    y = TOP0
    for label, body in d["items"]:
        T(sl, X0, y, 1.55, 0.30, label, size=12.5, font=MONO, color=CYAN, spc=120, wrap=False)
        T(sl, X0 + 1.75, y - 0.04, 9.55, 0.80, body, size=13, ls=1.30)
        y += max(0.58, 0.245 * (1 + len(body) // 52)) + 0.17
        RULE(sl, X0, y - 0.12, 11.3, a=7, h=0.008)


def s_table(sl, d):
    hd, rows = d["head"], d["rows"]
    cw = d["colw"]
    rh = d.get("rh", 0.40)
    y = TOP0
    # 表头
    cx = X0
    for i, h in enumerate(hd):
        T(sl, cx + 0.10, y, cw[i] - 0.14, 0.28, h,
          size=10.5, font=MONO, alpha=58, spc=60, wrap=False)
        cx += cw[i]
    RULE(sl, X0, y + 0.32, sum(cw), a=22, h=0.012)
    y += 0.46
    for ri, row in enumerate(rows):
        if ri % 2 == 0:
            R(sl, X0 - 0.10, y - 0.06, sum(cw) + 0.20, rh, fill=WHITE, alpha=3, radius=0.10)
        cx = X0
        for i, cell in enumerate(row):
            bold = (i == 0)
            col = CYAN if (d.get("accent_col") == i and ri == d.get("accent_row")) else WHITE
            T(sl, cx + 0.10, y + 0.02, cw[i] - 0.16, rh - 0.04, str(cell),
              size=d.get("fs", 11.5), bold=bold, color=col, ls=1.18,
              alpha=None if bold else 82)
            cx += cw[i]
        y += rh
        RULE(sl, X0, y - 0.03, sum(cw), a=6, h=0.006)
    if d.get("note"):
        T(sl, X0, min(BOT - 0.30, y + 0.16), 11.30, 0.60, d["note"], size=11, alpha=60, ls=1.25)


def s_cards(sl, d):
    items = d["items"]
    n = d.get("n", len(items))
    gap = 0.22
    cwid = (XW - gap * (n - 1)) / n
    hgt = d.get("h", 1.55)
    for r in range(0, len(items), n):
        chunk = items[r:r + n]
        y = TOP0 + (r // n) * (hgt + gap)
        for i, (head, body) in enumerate(chunk):
            x = X0 + i * (cwid + gap)
            CARD(sl, x, y, cwid, hgt)
            R(sl, x, y, 0.045, hgt, fill=CYAN)
            T(sl, x + 0.26, y + 0.20, cwid - 0.50, 0.30, head,
              size=14.5 if d.get("hsize", 14.5) else 14.5, bold=True, ls=1.15)
            T(sl, x + 0.26, y + 0.62, cwid - 0.50, hgt - 0.78, body,
              size=d.get("bsize", 11.5), alpha=76, ls=1.34)


def s_kv(sl, d):
    y = TOP0
    for k, v, sub in d["items"]:
        T(sl, X0, y - 0.02, 2.30, 0.30, k, size=12, font=MONO, alpha=58, wrap=False)
        T(sl, X0 + 2.50, y - 0.10, 3.20, 0.50, v, size=26, bold=True, color=CYAN, wrap=False)
        T(sl, X0 + 5.85, y + 0.02, 5.40, 0.44, sub, size=11.5, alpha=68, ls=1.30)
        y += 0.98
        RULE(sl, X0, y - 0.22, 11.3, a=8, h=0.008)


def s_steps(sl, d):
    y = TOP0 + 0.05
    for i, (tag, head, body) in enumerate(d["items"]):
        R(sl, X0, y, 0.62, 0.62, fill=CYAN, alpha=13, radius=0.22)
        T(sl, X0, y + 0.14, 0.62, 0.34, tag, size=15, font=MONO, color=CYAN,
          bold=True, align=CENTER, wrap=False)
        T(sl, X0 + 0.86, y + 0.02, 3.10, 0.32, head, size=14.5, bold=True, wrap=False)
        T(sl, X0 + 4.05, y + 0.05, 8.30, 0.60, body, size=11.5, alpha=76, ls=1.32)
        if i < len(d["items"]) - 1:
            DARK_VRULE(sl, X0 + 0.31, y + 0.66, 0.24)
        y += 0.92


def DARK_VRULE(sl, x, y, h):
    R(sl, x, y, 0.008, h, fill=CYAN, alpha=32)


def s_layers(sl, d):
    y = TOP0
    for name, body, col in d["items"]:
        R(sl, X0, y, 11.30, 0.86, fill=col, alpha=9, line=col, lw=1.0, radius=0.06)
        T(sl, X0 + 0.30, y + 0.14, 1.95, 0.30, name, size=13.5, bold=True, color=col, wrap=False)
        T(sl, X0 + 2.35, y + 0.16, 8.70, 0.60, body, size=11.5, alpha=80, ls=1.28)
        y += 1.02


def s_two(sl, d):
    """左右对照：左（传统/问题），右（我们/解法）"""
    cw = 5.45
    for i, (head, col, items) in enumerate(d["cols"]):
        x = X0 + i * (cw + 0.43)
        CARD(sl, x, TOP0, cw, 4.55)
        R(sl, x, TOP0, cw, 0.055, fill=col)
        T(sl, x + 0.34, TOP0 + 0.36, cw - 0.68, 0.34, head, size=15, bold=True, color=col, wrap=False)
        y = TOP0 + 0.95
        for it in items:
            R(sl, x + 0.34, y + 0.11, 0.05, 0.17, fill=col)
            T(sl, x + 0.54, y + 0.02, cw - 1.0, 0.56, it, size=12, alpha=82, ls=1.30)
            y += 0.30 * (1 + len(it) // 22) + 0.20
    if d.get("foot"):
        T(sl, X0, 6.32, 11.3, 0.40, d["foot"], size=12, color=AMBER, ls=1.3)


def s_closing(sl, d):
    R(sl, 0, 0, W, H, fill=BG)
    BAR(sl)
    T(sl, X0, 1.88, 11.2, 2.00, d["big"], size=31, bold=True, ls=1.34)
    RULE(sl, X0, 4.12, 6.4, a=20, h=0.012)
    y = 4.44
    for line in d["meta"]:
        T(sl, X0, y, 11.2, 0.32, line, size=12.5, alpha=68)
        y += 0.42
    T(sl, X0, 6.60, 11.2, 0.30, "神麻组 · 雨证 RainProof · 2026.11", size=11.5, font=MONO, alpha=38)


